create schema ambmao;
set local search_path to ambmao;

-- Schema privado da aplicação; não expor ambmao na Data API do Supabase.
create table cartilha (
    codigo bigint generated by default as identity primary key,
    nome_doenca varchar(160) not null,
    nome_busca varchar(160) not null,
    o_que_e text not null,
    sinais_sintomas text not null,
    orientacoes_gerais text not null,
    fonte_titulo varchar(200),
    fonte_url varchar(2000),
    criado_em timestamp with time zone not null,
    atualizado_em timestamp with time zone not null,
    constraint cartilha_nome_valido check (length(trim(nome_doenca)) > 0),
    constraint cartilha_conteudo_valido check (length(trim(o_que_e)) > 0 and length(trim(sinais_sintomas)) > 0 and length(trim(orientacoes_gerais)) > 0)
);
create index ix_cartilha_nome_busca on cartilha(nome_busca);

create table profissional (
    codigo bigint generated by default as identity primary key,
    nome varchar(160) not null,
    email varchar(254) not null unique,
    senha_hash varchar(255) not null,
    ativo boolean not null default true
);

-- Somente o backend acessa este schema; nao expor pela Data API.
revoke all on schema ambmao from public, anon, authenticated;
revoke all on all tables in schema ambmao from public, anon, authenticated;
revoke all on all sequences in schema ambmao from public, anon, authenticated;
